create table if not exists public.registrations (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  registration_number text not null,
  food_preference text not null check (food_preference in ('Veg', 'Non-Veg')),
  registration_code text not null unique,
  email_status text not null default 'pending' check (email_status in ('pending', 'sent', 'failed')),
  email_message_id text,
  checked_in boolean not null default false,
  checked_in_at timestamptz,
  created_at timestamptz not null default now()
);

alter table public.registrations add column if not exists checked_in boolean not null default false;
alter table public.registrations add column if not exists checked_in_at timestamptz;

create unique index if not exists registrations_registration_number_key
  on public.registrations (lower(registration_number));

create index if not exists registrations_email_idx
  on public.registrations (lower(email));

create index if not exists registrations_checkin_idx
  on public.registrations (checked_in, created_at desc);

alter table public.registrations enable row level security;

-- No public SELECT/INSERT policies are created intentionally.
-- The Vercel functions use the Supabase service-role key server-side.
